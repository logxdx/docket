#!/usr/bin/env python3
"""Write integration_test/speech_fixture.dart from a 16-bit mono WAV, so the
on-device test has speech without pushing files into the app first.

    python3 -I tool/make_speech_fixture.py third_party/desert-ant-core/packages/voz-node/test/fixtures/speech.wav

The output is generated (and gitignored): the WAV is Desert Ant's own test
fixture, under its licence, and is not part of the app.
"""
import base64
import os
import sys
import wave

src = sys.argv[1]
with wave.open(src, "rb") as w:
    assert w.getsampwidth() == 2 and w.getnchannels() == 1, "16-bit mono WAV only"
    rate = w.getframerate()
with open(src, "rb") as f:
    data = base64.b64encode(f.read()).decode()
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "integration_test", "speech_fixture.dart")
with open(out, "w") as f:
    f.write("// Generated by tool/make_speech_fixture.py from %s. Do not edit.\n" % os.path.basename(src))
    f.write("const speechRate = %d;\n" % rate)
    f.write("const speechWavBase64 =\n")
    for i in range(0, len(data), 120):
        f.write("    '%s'%s\n" % (data[i:i + 120], ";" if i + 120 >= len(data) else ""))
print("wrote", out, rate, "Hz")
